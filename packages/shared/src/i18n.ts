export function translate(lang: Lang, text: string, vars?: Record<string, string | number>) {
  if (!text) return text;
  const table = lang === 'en' ? en : rw;
  let out = table[text] ?? text;
  if (vars) {
    for (const [key, value] of Object.entries(vars)) out = out.replaceAll(`{${key}}`, String(value));
  }
  return out;
}
